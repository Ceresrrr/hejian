const oldVol = fs.readFileSync(volFile, 'utf8').replace(/^\uFEFF/, '').split(/\r?\n/)
  .filter(l => l.trim() && !l.startsWith('#'));
const CIVIL = { v: '中国', e: '欧洲' };
const volRows = oldVol.map(l => {
  const c = l.split('\t');
  return [c[0], c[1], c[2], c[3], c[4], CIVIL[c[0][0]] || c[5] || ''];
}).concat(VOLS);
volRows.sort((a, b) => +a[4] - +b[4]);
